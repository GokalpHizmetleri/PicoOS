#!/usr/bin/env python3
"""Bundle the PicoOS web UI into firmware/picoos/assets.py.

Every file is gzip-compressed and stored as a bytes literal. When the module is
frozen into the firmware those bytes live in flash (not RAM) and are streamed
to the browser with `Content-Encoding: gzip`.
"""
import gzip
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "firmware", "web")
OUT = os.path.join(ROOT, "firmware", "picoos", "assets.py")

FILES = {
    "/index.html": ("dashboard/index.html", "text/html; charset=utf-8"),
    "/app.css": ("dashboard/app.css", "text/css; charset=utf-8"),
    "/app.js": ("dashboard/app.js", "application/javascript; charset=utf-8"),
    "/setup.html": ("setup/setup.html", "text/html; charset=utf-8"),
    "/favicon.svg": ("favicon.svg", "image/svg+xml"),
}


def main():
    lines = [
        "# AUTO-GENERATED by tools/build_assets.py - do not edit.",
        "# Gzip-compressed PicoOS web UI, frozen into flash.",
        "FILES = {",
    ]
    total_raw = total_gz = 0
    for route, (rel, ctype) in FILES.items():
        with open(os.path.join(WEB, rel), "rb") as f:
            raw = f.read()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total_raw += len(raw)
        total_gz += len(gz)
        lines.append("    %r: (%r, %r)," % (route, ctype, gz))
        print("  %-14s %7d -> %6d bytes" % (route, len(raw), len(gz)))
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("assets.py: %d bytes of web UI, %d bytes gzipped" % (total_raw, total_gz))
    return 0


if __name__ == "__main__":
    sys.exit(main())
